-- ========================================================================
-- Tables, created parents first so every foreign key has a table to point at
-- ========================================================================

-- Table artist: An independent musician or group that has registered with the
-- service to upload recordings under a direct streaming licence, and is paid
-- a per stream royalty on plays of those recordings. An artist may be
-- registered before uploading a first recording.
CREATE TABLE artist (
  artist_id MEDIUMINT UNSIGNED NOT NULL,
  stage_name VARCHAR(64) NOT NULL,
  country CHAR(2),
  joined_date DATE NOT NULL,
  payout_rate DECIMAL(5,5) NOT NULL,
  verified BIT(1) NOT NULL,
  PRIMARY KEY (artist_id),
  UNIQUE KEY uq_artist_stage_name (stage_name),
  CONSTRAINT ck_artist_1 CHECK (payout_rate > 0)
) ENGINE=InnoDB;

-- Table track: A single audio recording uploaded by an artist, held in the
-- catalogue and made available for streaming once it has been scored by at
-- least one model. The audio file itself is held in an object store under a
-- key computed from the Track ID, so no column stores its location.
-- Created after artist, which its foreign key references.
CREATE TABLE track (
  track_id INT UNSIGNED NOT NULL,
  artist_id MEDIUMINT UNSIGNED NOT NULL,
  title VARCHAR(128) NOT NULL,
  duration SMALLINT UNSIGNED NOT NULL,
  release_date DATE NOT NULL,
  audio_checksum BINARY(32) NOT NULL,
  ingest_status ENUM('awaiting scoring', 'scored', 'rejected') NOT NULL,
  PRIMARY KEY (track_id),
  UNIQUE KEY uq_track_audio_checksum (audio_checksum),
  CONSTRAINT fk_track_artist FOREIGN KEY (artist_id) REFERENCES artist (artist_id),
  CONSTRAINT ck_track_1 CHECK (duration > 0)
) ENGINE=InnoDB;

-- Table genre: One of the fixed set of musical categories over which every
-- scoring model produces its probability distribution, forming the coordinate
-- system in which listeners describe the blend they want.
CREATE TABLE genre (
  genre_id TINYINT UNSIGNED NOT NULL,
  name VARCHAR(9) NOT NULL,
  description VARCHAR(80),
  PRIMARY KEY (genre_id),
  UNIQUE KEY uq_genre_name (name),
  CONSTRAINT ck_genre_1 CHECK (genre_id BETWEEN 0 AND 9)
) ENGINE=InnoDB;

-- Table listener: A registered subscriber who streams recordings from the
-- catalogue and defines the stations through which they discover new
-- material.
CREATE TABLE listener (
  listener_id INT UNSIGNED NOT NULL,
  email VARCHAR(254) NOT NULL,
  display_name VARCHAR(32) NOT NULL,
  plan_tier ENUM('free', 'standard', 'premium') NOT NULL,
  signup_date DATE NOT NULL,
  PRIMARY KEY (listener_id),
  UNIQUE KEY uq_listener_email (email)
) ENGINE=InnoDB;

-- Table scoring_model: A specific trained and deployed version of the machine
-- learning system that places recordings in genre space. Several versions are
-- in service at once because they differ in architecture and therefore
-- disagree with one another, and that disagreement is itself used as a
-- signal.
CREATE TABLE scoring_model (
  model_id TINYINT UNSIGNED NOT NULL,
  version_label VARCHAR(32) NOT NULL,
  fusion_type ENUM('concat', 'gated') NOT NULL,
  embedding_dimension SMALLINT UNSIGNED NOT NULL,
  segment_length TINYINT UNSIGNED NOT NULL,
  training_corpus VARCHAR(16) NOT NULL,
  holdout_accuracy DECIMAL(5,4) NOT NULL,
  deployed_on DATE NOT NULL,
  PRIMARY KEY (model_id),
  UNIQUE KEY uq_scoring_model_version_label (version_label),
  CONSTRAINT ck_scoring_model_1 CHECK (holdout_accuracy BETWEEN 0 AND 1),
  CONSTRAINT ck_scoring_model_2 CHECK (segment_length > 0),
  CONSTRAINT ck_scoring_model_3 CHECK (embedding_dimension > 0)
) ENGINE=InnoDB;

-- Table station: A standing description of a region of genre space created by
-- a listener. A station stores the blend and the ambiguity range the listener
-- wants rather than a fixed list of recordings, so its contents change as the
-- catalogue grows.
-- Created after listener, scoring_model, which its foreign keys reference.
CREATE TABLE station (
  station_id INT UNSIGNED NOT NULL,
  listener_id INT UNSIGNED NOT NULL,
  model_id TINYINT UNSIGNED NOT NULL,
  name VARCHAR(64) NOT NULL,
  minimum_ambiguity DECIMAL(3,2) NOT NULL,
  maximum_ambiguity DECIMAL(3,2) NOT NULL,
  created_on DATE NOT NULL,
  PRIMARY KEY (station_id),
  CONSTRAINT fk_station_listener FOREIGN KEY (listener_id) REFERENCES listener (listener_id),
  CONSTRAINT fk_station_scoring_model FOREIGN KEY (model_id) REFERENCES scoring_model (model_id),
  CONSTRAINT ck_station_1 CHECK (minimum_ambiguity BETWEEN 0 AND 1),
  CONSTRAINT ck_station_2 CHECK (maximum_ambiguity BETWEEN 0 AND 1),
  CONSTRAINT ck_station_3 CHECK (minimum_ambiguity <= maximum_ambiguity)
) ENGINE=InnoDB;

-- Table track_score: The result one scoring model produced for one recording.
-- This is the associative entity that resolves the many to many relationship
-- between recordings and scoring models, and it is the parent record for
-- every model output: the full genre distribution is held in Genre
-- Probability rows that belong to it. No genre is ever recorded against a
-- recording on its own, because a placement is a property of the pair of
-- recording and model and not of the recording alone. The full distribution
-- is held in Genre Probability; Genre ID, Top Probability, Posterior Entropy
-- and Model Divergence are summaries derived from it and stored on this row
-- so that stations can filter without reading ten rows per score. A result is
-- written once, in the same transaction as its distribution, and is replaced
-- whole on a rescore, so the stored summaries cannot drift from the
-- distribution. The model's vector representation of the recording is held in
-- a vector store under a key computed from the same Track ID and Model ID, so
-- no column stores it.
-- Created after track, scoring_model, genre, which its foreign keys
-- reference.
CREATE TABLE track_score (
  track_id INT UNSIGNED NOT NULL,
  model_id TINYINT UNSIGNED NOT NULL,
  genre_id TINYINT UNSIGNED NOT NULL COMMENT 'Derived: genre with the highest probability in this score''s Genre Probability rows (I3)',
  top_probability DECIMAL(5,4) NOT NULL COMMENT 'Derived: largest of this score''s ten probabilities (I3)',
  posterior_entropy DECIMAL(5,4) NOT NULL COMMENT 'Derived: Shannon entropy of the ten probabilities / log(10) (I3)',
  model_divergence DECIMAL(5,4) COMMENT 'Derived: mean Jensen-Shannon divergence from the other models'' distributions for this track (I3)',
  segment_variance DECIMAL(4,4),
  scored_on DATETIME NOT NULL,
  PRIMARY KEY (track_id, model_id),
  CONSTRAINT fk_track_score_track FOREIGN KEY (track_id) REFERENCES track (track_id),
  CONSTRAINT fk_track_score_scoring_model FOREIGN KEY (model_id) REFERENCES scoring_model (model_id),
  CONSTRAINT fk_track_score_genre FOREIGN KEY (genre_id) REFERENCES genre (genre_id),
  CONSTRAINT ck_track_score_1 CHECK (top_probability BETWEEN 0 AND 1),
  CONSTRAINT ck_track_score_2 CHECK (posterior_entropy BETWEEN 0 AND 1),
  CONSTRAINT ck_track_score_3 CHECK (model_divergence IS NULL OR model_divergence BETWEEN 0 AND 1),
  CONSTRAINT ck_track_score_4 CHECK (segment_variance IS NULL OR segment_variance BETWEEN 0 AND 0.25)
) ENGINE=InnoDB;

-- Table play: A single occasion on which a listener streamed a recording.
-- This is the associative entity that resolves the many to many relationship
-- between listeners and recordings, and it serves two purposes at once: it is
-- the record from which listener taste is inferred and it is the billable
-- event on which the artist royalty is calculated.
-- Created after listener, track, station, which its foreign keys reference.
CREATE TABLE play (
  listener_id INT UNSIGNED NOT NULL,
  track_id INT UNSIGNED NOT NULL,
  played_at DATETIME NOT NULL,
  station_id INT UNSIGNED,
  seconds_played SMALLINT UNSIGNED NOT NULL,
  completed BIT(1) NOT NULL COMMENT 'Derived: 1 exactly when seconds_played = track.duration (I7)',
  reaction ENUM('saved', 'skipped'),
  royalty_amount DECIMAL(5,5) NOT NULL COMMENT 'Snapshot: artist payout_rate at play time if seconds_played >= 30, else 0 (I7)',
  PRIMARY KEY (listener_id, track_id, played_at),
  CONSTRAINT fk_play_listener FOREIGN KEY (listener_id) REFERENCES listener (listener_id),
  CONSTRAINT fk_play_track FOREIGN KEY (track_id) REFERENCES track (track_id),
  CONSTRAINT fk_play_station FOREIGN KEY (station_id) REFERENCES station (station_id),
  CONSTRAINT ck_play_1 CHECK (royalty_amount >= 0)
) ENGINE=InnoDB;

-- Table station_blend: The weight one station gives to one genre. This is the
-- associative entity that resolves the many to many relationship between
-- stations and genres: a station blends several genres and a genre appears in
-- many stations. Holding one weight per row keeps every value atomic, which a
-- single multi-valued blend field on the station could not.
-- Created after station, genre, which its foreign keys reference.
CREATE TABLE station_blend (
  station_id INT UNSIGNED NOT NULL,
  genre_id TINYINT UNSIGNED NOT NULL,
  weight DECIMAL(3,2) NOT NULL,
  PRIMARY KEY (station_id, genre_id),
  CONSTRAINT fk_station_blend_station FOREIGN KEY (station_id) REFERENCES station (station_id),
  CONSTRAINT fk_station_blend_genre FOREIGN KEY (genre_id) REFERENCES genre (genre_id),
  CONSTRAINT ck_station_blend_1 CHECK (weight > 0 AND weight <= 1)
) ENGINE=InnoDB;

-- Table genre_probability: The probability one scoring model assigned to one
-- genre for one recording. This is the associative entity that resolves the
-- many to many relationship between scoring results and genres: a result
-- assigns a probability to every genre, and a genre receives a probability in
-- every result. It holds the full distribution that stations match against,
-- which the single top genre on Track Score cannot express.
-- Created after track_score, genre, which its foreign keys reference.
CREATE TABLE genre_probability (
  track_id INT UNSIGNED NOT NULL,
  model_id TINYINT UNSIGNED NOT NULL,
  genre_id TINYINT UNSIGNED NOT NULL,
  probability DECIMAL(5,4) NOT NULL,
  PRIMARY KEY (track_id, model_id, genre_id),
  CONSTRAINT fk_genre_probability_track_score FOREIGN KEY (track_id, model_id) REFERENCES track_score (track_id, model_id),
  CONSTRAINT fk_genre_probability_genre FOREIGN KEY (genre_id) REFERENCES genre (genre_id),
  CONSTRAINT ck_genre_probability_1 CHECK (probability BETWEEN 0 AND 1)
) ENGINE=InnoDB;

