"""Build the Project 2 plan: validate plan/plan.json, write data/plan.js and README.md.

plan.json is the single source for the brief's requirements, the to-do list and the
deliverable list. Every to-do names the requirement(s) it serves; this script fails if
a to-do names an unknown requirement or a requirement has no to-do. Deliverable status
comes from the files actually present in deliverables/ (and submission/ for the zip).
Run from the repository root or anywhere:
    python project2/scripts/build_plan.py
"""
import json, os, sys

P2 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(P2, "plan", "plan.json")
STATUS_MARK = {"done": "[x]", "partial": "[~]", "open": "[ ]"}

print("[1/4] reading plan/plan.json", flush=True)
plan = json.load(open(SRC, encoding="utf-8"))
reqs = {r["id"]: r for r in plan["requirements"]}
tasks = {t["id"]: t for t in plan["tasks"]}

print("[2/4] checking to-do <-> requirement links", flush=True)
errors = []
for t in plan["todos"]:
    if t["task"] not in tasks: errors.append(f"to-do {t['id']}: unknown task {t['task']}")
    if t["status"] not in STATUS_MARK: errors.append(f"to-do {t['id']}: bad status {t['status']}")
    for r in t["reqs"]:
        if r not in reqs: errors.append(f"to-do {t['id']}: unknown requirement {r}")
for r in reqs:
    if not any(r in t["reqs"] for t in plan["todos"]):
        errors.append(f"requirement {r} has no to-do")
for d in plan["deliverables"]:
    for r in d["reqs"]:
        if r not in reqs: errors.append(f"deliverable {d['file']}: unknown requirement {r}")
if errors:
    print("      FAILED\n      " + "\n      ".join(errors)); sys.exit(1)
print(f"      {len(plan['todos'])} to-dos, {len(reqs)} requirements, every requirement covered", flush=True)

print("[3/4] checking deliverable files", flush=True)
for d in plan["deliverables"]:
    where = "submission" if d.get("zip") else "deliverables"
    d["present"] = os.path.isfile(os.path.join(P2, where, d["file"]))
    d["path"] = f"{where}/{d['file']}"
    print(f"      {'present' if d['present'] else 'missing'}  {d['path']}", flush=True)

js = "/* Generated by project2/scripts/build_plan.py from plan/plan.json; do not edit by hand. */\n"
js += "window.PLAN = " + json.dumps(plan, indent=1, ensure_ascii=False) + ";\n"
os.makedirs(os.path.join(P2, "data"), exist_ok=True)
open(os.path.join(P2, "data", "plan.js"), "w", encoding="utf-8", newline="\n").write(js)

print("[4/4] writing README.md", flush=True)
n_done = sum(t["status"] == "done" for t in plan["todos"])
n_part = sum(t["status"] == "partial" for t in plan["todos"])
n_del = sum(d["present"] for d in plan["deliverables"])
L = [f"# {plan['project']}", "",
     f"{plan['group']} ({'; '.join(plan['members'])}). Due **{plan['due_text']}**.", "",
     "Site: https://n-herling-mk1.github.io/INFO_579_Fa26_Proj1_CROSSFADE/project2/  ",
     f"Brief: [`{plan['brief']}`]({plan['brief']})", "",
     "> Generated by `scripts/build_plan.py` from `plan/plan.json`. Edit the JSON, then rerun the script.", "",
     f"**Progress:** {n_done} of {len(plan['todos'])} to-dos done, {n_part} in progress. "
     f"{n_del} of {len(plan['deliverables'])} deliverables present.", "",
     "## Deliverables", "",
     "| File | Task | Weight | Requirements | Status |", "|---|---|---|---|---|"]
for d in plan["deliverables"]:
    t = tasks[d["task"]]
    w = f"{t['weight']}%" if t["weight"] else ""
    L.append(f"| `{d['file']}` | {t['id']} {t['title']} | {w} | {', '.join(d['reqs'])} | "
             f"{'present' if d['present'] else 'not yet'} |")
L += ["", "## To-do", "", "`[x]` done, `[~]` in progress, `[ ]` open. Requirement IDs refer to the table below.", ""]
for t in plan["tasks"]:
    head = f"### {t['id']} {t['title']}" + (f" ({t['weight']}%, `{t['file']}`)" if t["file"] else "")
    L += [head, ""]
    for td in [x for x in plan["todos"] if x["task"] == t["id"]]:
        L.append(f"- {STATUS_MARK[td['status']]} **{td['title']}** `{' '.join(td['reqs'])}`  ")
        L.append(f"  {td['detail']}")
    L.append("")
L += ["## Requirements (from the brief)", "", "| ID | Requirement | To-dos |", "|---|---|---|"]
for r in plan["requirements"]:
    ids = [t["id"] for t in plan["todos"] if r["id"] in t["reqs"]]
    L.append(f"| {r['id']} | {r['text']} | {', '.join(ids)} |")
L += ["", "## Project 1 feedback", "", plan["feedback"], "",
      "## Layout", "", "```",
      "plan/plan.json          requirements, to-dos, deliverables (the source)",
      "scripts/build_plan.py   validates the plan, writes data/plan.js and this README",
      "data/plan.js            generated; read by the site panels",
      "panels/                 site panels: home, to-do, requirements, deliverables, brief",
      "brief/                  the assignment brief (PDF)",
      "deliverables/           the four .sql files as they are finished",
      "submission/             project02_info579_group_1.zip", "```", ""]
open(os.path.join(P2, "README.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L))
print(f"      done: {n_done}/{len(plan['todos'])} to-dos done, {n_del}/{len(plan['deliverables'])} deliverables present", flush=True)
